import { formatCost, formatMs } from "@/lib/format";
import type { ResearchView } from "@/lib/schemas";

/** What the run cost and who made it (course §2.3 cost management, §2.10 accountability). */
export default function MetaBar({ run }: { run: ResearchView }) {
  const m = run.metadata;
  const models = [...new Set(Object.values(m.models).filter(Boolean))].join(", ") || "—";
  const items: [string, string][] = [
    ["Generated by", m.generated_by],
    ["Duration", m.duration_seconds !== null ? formatMs(m.duration_seconds * 1000) : "—"],
    ["LLM calls", `${m.llm_calls} real · ${m.cached_calls} cached`],
    ["Tool calls", String(m.tool_calls)],
    ["Evidence", String(m.evidence)],
    ["Tokens", `${(m.tokens.input + m.tokens.output).toLocaleString("en-US")} (${m.tokens.input.toLocaleString("en-US")} in · ${m.tokens.output.toLocaleString("en-US")} out)`],
    ["Est. cost", `${formatCost(m.est_cost_usd)} at paid prices`],
    ["Models", models],
    ["Prompt version", `v${m.prompt_version || "?"}`],
    ["Decisions", `${m.iterations} of ${m.iteration_limit}`],
  ];
  if (m.grounding) items.push(["Grounding", `${m.grounding.supported} of ${m.grounding.checked} claims supported`]);
  return (
    <dl aria-label="Run metadata" className="grid grid-cols-1 gap-x-4 gap-y-1 text-xs sm:grid-cols-2">
      {items.map(([k, v]) => (
        <div key={k} className="flex min-w-0 gap-2">
          <dt className="shrink-0 text-zinc-600 dark:text-zinc-400">{k}:</dt>
          <dd className="min-w-0 break-words text-zinc-900 dark:text-zinc-100">{v}</dd>
        </div>
      ))}
    </dl>
  );
}
